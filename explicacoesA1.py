    if nivel == 1:
        match letra:
            case "A":
                print("VERB TO BE")
            case "B":
                print("PRESENT SIMPLE")
            case "C":
                print("PRESENT CONTINUOUS")
            case "D":
                print("MODAL CAN/CAN'T")
            case "E":
                print("PRONOMES PESSOAIS")
            case "F":
                print("PRONOMES E ADJETIVOS POSSESSIVOS")
            case "G":
                print("PRONOMES DEMONSTRATIVOS")
            case "H":
                print("WH-QUESTIONS")
            case "I":
                print("ARTIGOS")
            case "J":
                print("SUBSTANTIVOS PLURAIS")
            case "K":
                print("PREPOSIÇÕES DE LUGAR BÁSICAS")
